/**
 * Generates styles/tokens.css from styles/tokens.json.
 * Run with `pnpm tokens` (or `make tokens`). The output is committed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

type Themed = { light: string; dark: string };
type Tokens = {
  color: { tokens: { name: string; value: Themed }[] };
  type: {
    families: Record<string, string>;
    groups: {
      styles: {
        name: string;
        fontSize: string;
        lineHeight: number;
        fontWeight: number;
        letterSpacing?: string;
      }[];
    }[];
  };
  spacing: { tokens: { name: string; value: string }[] };
  radius: { tokens: { name: string; value: string }[] };
  shadow: { tokens: { name: string; value: Themed }[] };
  size: { tokens: { name: string; value: string }[] };
};

/** next/font exposes the self-hosted families through these variables (see app/fonts.ts). */
const FONT_VARS: Record<string, string> = {
  display: '--nf-display',
  sans: '--nf-sans',
  mono: '--nf-mono',
};

export function buildTokensCss(tokens: Tokens): string {
  const light: string[] = [];
  const dark: string[] = [];
  const statics: string[] = [];

  for (const t of tokens.color.tokens) {
    light.push(`  --${t.name}: ${t.value.light};`);
    dark.push(`  --${t.name}: ${t.value.dark};`);
  }
  for (const t of tokens.shadow.tokens) {
    light.push(`  --${t.name}: ${t.value.light};`);
    dark.push(`  --${t.name}: ${t.value.dark};`);
  }
  for (const [name, stack] of Object.entries(tokens.type.families)) {
    const v = FONT_VARS[name];
    statics.push(`  --font-${name}: ${v ? `var(${v}), ` : ''}${stack};`);
  }
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      statics.push(`  --text-${s.name}: ${s.fontSize};`);
      statics.push(`  --text-${s.name}--line-height: ${s.lineHeight};`);
      statics.push(`  --text-${s.name}--font-weight: ${s.fontWeight};`);
      if (s.letterSpacing) statics.push(`  --text-${s.name}--letter-spacing: ${s.letterSpacing};`);
    }
  }
  for (const t of [...tokens.spacing.tokens, ...tokens.radius.tokens, ...tokens.size.tokens]) {
    statics.push(`  --${t.name}: ${t.value};`);
  }

  return `/* Generated by scripts/build-tokens.ts from styles/tokens.json. Do not edit. */

:root {
  color-scheme: light;
${statics.join('\n')}
${light.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${dark.map((l) => '  ' + l).join('\n')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${dark.join('\n')}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = new URL('../styles/tokens.json', import.meta.url);
  const out = new URL('../styles/tokens.css', import.meta.url);
  const tokens = JSON.parse(readFileSync(src, 'utf8')) as Tokens;
  writeFileSync(out, buildTokensCss(tokens));
  console.log(`Wrote ${fileURLToPath(out)}`);
}
