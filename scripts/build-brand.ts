/**
 * Converts the "m" of the app icon into an SVG path, so icons render identically where web
 * fonts are unavailable (favicons, apple-icon).
 * Outputs lib/brand/paths.generated.ts and app/icon.svg. Run with `pnpm brand`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const FONT =
  'node_modules/@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-800-normal.woff';

/** "m" glyph centred in a 100×100 box. */
function mGlyph(font: opentype.Font, fs: number) {
  const path = font.getPath('m', 0, 0, fs);
  const bb = path.getBoundingBox();
  const dx = 50 - (bb.x1 + bb.x2) / 2;
  const dy = 50 - (bb.y1 + bb.y2) / 2;
  return font.getPath('m', dx, dy, fs).toPathData(2);
}

export function build() {
  const buf = readFileSync(FONT);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const m = mGlyph(font, 62);

  const ts = `/* Generated by scripts/build-brand.ts. Do not edit. */
/** "m" glyph (Bricolage Grotesque 800) centred in a 100×100 box. */
export const M_GLYPH_PATH = ${JSON.stringify(m)};
`;
  writeFileSync(new URL('../lib/brand/paths.generated.ts', import.meta.url), ts);

  // App icon: "m" on a lime square tilted by -3°.
  const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><g transform="rotate(-3 50 50)"><rect x="6" y="6" width="88" height="88" rx="24" fill="#d4f75a"/><path d="${m}" fill="#16131f"/></g></svg>\n`;
  writeFileSync(new URL('../app/icon.svg', import.meta.url), icon);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  build();
  console.log('Wrote lib/brand/paths.generated.ts and app/icon.svg');
}
